//======================================================================
// BinToBcdN — позиционный код катодов -> 8-4-2-1 активным нулём
//----------------------------------------------------------------------
// TC-O3 (TRS v0.38): четыре ИЛИ-НЕ без выходных инверторов. Выход Out_n —
// инверсные тетрады; память, терминал и эмулятор принимают их так
// (ОЗУ и память программ инвертируют на своих портах, эмулятор — на
// границе DekatronPC). Прямой BinToBcd остаётся для старых блоков и теста
// кодека.
//======================================================================
module BinToBcdN(
    //verilator lint_off UNUSEDSIGNAL
    input  wire [9:0] In,     // позиционный код, In[0] не участвует
    //verilator lint_on UNUSEDSIGNAL
    output wire [3:0] Out_n   // ~(8-4-2-1)
    );

    nor nor1 (Out_n[0], In[1], In[3], In[5], In[7], In[9]);
    nor nor2 (Out_n[1], In[2], In[3], In[6], In[7]);
    nor nor3 (Out_n[2], In[4], In[5], In[6], In[7]);
    nor nor4 (Out_n[3], In[8], In[9]);

endmodule
