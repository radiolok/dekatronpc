#!/usr/bin/env python3
"""6Kh7B (6Х7Б) diode model from the reference data (sch/tubes/6Kh7B/README.md), and its check in ngspice.

usage: tools/spice/fit_6kh7b.py [--sub sch/libs/6Kh7B.sub] [--case nom|leaky]

One diode per subcircuit (KiCad symbol vacuum_tube:6Х7Б, one unit per diode):
  Ia = P * sp(Ua + VC)^1.5,  sp(x) = S*ln(1 + exp(x/S))
Above ~0.5 V this is Child's law; below it is the retarding-field region, Ia ~ exp(Ua/VT) with
VT = S/1.5 = kT/q of an oxide cathode (~1050 K). VC is the contact potential (an effective forward
bias at Ua = 0). Only two numbers of the sheet constrain it:
  emission current at Ua = 10 V        >= 35 mA   -> P
  initial anode current at Ua = 0, Rload = 40 kOhm  <= 20 uA   -> VC
Both are bounds, not typical values. "leaky" puts the initial current at the bound (20 uA),
"nom" at 5 uA; P is taken at the emission bound in both, so it is a weak (pessimistic) diode for
the forward direction. Capacitance A-K 5.8 pF (the sheet's maximum); insulation 100 MOhm.
"""
import math, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
VT = 8.617e-5 * 1050          # kT/q at the cathode
S = 1.5 * VT
P = 35e-3 / 10 ** 1.5         # emission bound at 10 V (Child's law)
I0 = {"nom": 5e-6, "leaky": 20e-6}


def sp(x):
    return S * math.log1p(math.exp(x / S)) if x < 30 * S else x


def ia(u, vc):
    return P * sp(u + vc) ** 1.5


def vc_for(i_target, r=40e3):
    """VC such that the diode shorted through r carries i_target: Ua = -i*r."""
    lo, hi = -2.0, 2.0
    for _ in range(100):
        vc = (lo + hi) / 2
        # current through r at this VC: solve i = ia(-i r, vc) by bisection on i
        a, b = 0.0, 1e-3
        for _ in range(100):
            i = (a + b) / 2
            a, b = (i, b) if ia(-i * r, vc) > i else (a, i)
        lo, hi = (vc, hi) if i < i_target else (lo, vc)
    return vc


def sub_text(vc, case):
    return "\r\n".join([
        "*--------------------------------------------------------------------------",
        "* 6Kh7B (6Х7Б) double diode, one diode, behavioural model, ngspice syntax",
        f"* Generated by tools/spice/fit_6kh7b.py --case {case} from the reference",
        "* data in sch/tubes/6Kh7B/README.md (emission >= 35 mA at 10 V; initial",
        f"* current at Ua = 0, 40 kOhm: {I0[case] * 1e6:.0f} uA, the sheet says <= 20 uA).",
        "* Pins: A K (heater not modelled). KiCad vacuum_tube:6Х7Б: unit A 1=A 3=K,",
        "* unit B 7=A 5=K.",
        "* Ia = P*sp(Ua + VC)^1.5, sp(x) = S*ln(1 + exp(x/S)); VT = S/1.5 = kT/q (1050 K)",
        "* Not fitted to a measured curve: Рис. 539 of the handbook is unreadable.",
        "*--------------------------------------------------------------------------",
        ".SUBCKT 6Kh7B A K",
        f"+ PARAMS: P={P:.6g} VC={vc:.6g} S={S:.6g} CAK=5.8P",
        "BA A K I={P*PWR(S*LN(1 + EXP(MIN(V(A,K) + VC, 30*S)/S)) + MAX(V(A,K) + VC - 30*S, 0), 1.5)}",
        "RAK A K 100MEG",
        "CAK A K {CAK}",
        ".ENDS 6Kh7B",
        "* Both diodes of one tube, for the two-unit KiCad symbol: Sim.Pins \"1=A1 3=K1 7=A2 5=K2\"",
        ".SUBCKT 6Kh7B2 A1 K1 A2 K2",
        "X1 A1 K1 6Kh7B",
        "X2 A2 K2 6Kh7B",
        ".ENDS 6Kh7B2", ""])


def check(path):
    deck = f"""* 6Kh7B check
.include "{path}"
Va a 0 0
X1 a k 6Kh7B
Rl k 0 40k
V10 b 0 10
X2 b 0 6Kh7B
.control
op
print -v(k)/40k i(V10)
.endc
.end
"""
    with tempfile.NamedTemporaryFile("w", suffix=".cir", delete=False) as f:
        f.write(deck)
    out = subprocess.run([sys.executable, os.path.join(HERE, "ngrun.py"), f.name, "quit"],
                         capture_output=True, text=True).stdout
    os.unlink(f.name)
    return out


if __name__ == "__main__":
    case = sys.argv[sys.argv.index("--case") + 1] if "--case" in sys.argv else "leaky"
    vc = vc_for(I0[case])
    print(f"case {case}: P = {P:.4g} A/V^1.5, S = {S:.4g} V (VT {VT * 1e3:.1f} mV), VC = {vc:.4f} V")
    for u in (-2, -1, -0.5, 0, 0.5, 1, 10):
        print(f"  Ua {u:5.1f} V: Ia {ia(u, vc):.4g} A")
    if "--sub" in sys.argv:
        path = sys.argv[sys.argv.index("--sub") + 1]
        open(path, "w", newline="").write(sub_text(vc, case))
        print("wrote", path)
        print(check(os.path.abspath(path)))
