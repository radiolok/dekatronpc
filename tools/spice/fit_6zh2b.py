#!/usr/bin/env python3
"""Fit the behavioural 6Zh2B model (sch/libs/6Zh2B.sub) to the digitized curves
(doc/data/6zh2b_datasheet.json, Рис. 215 and 216). doc/nand2_j2_6zh2b.md, Model.

Space current (power law, cut-off set by g1, g2 and g3):
    Ik = K * sp(Ug1 + Ug2/MU2 + Ug3/MU3 + Ua/MUA, S0) ^ EX
Plate share, g3 and the plate knee:
    F  = FM * tanh(sp(Ug3 + Ua/D - U0 - U1*Ik, S3) / W3) * tanh(max(Ua, 0) / (VA0 + VA1*Ik))   (Ik in mA)
    Ia = Ik * F,   Ig2 = Ik * (1 - F)
sp(x, s) = s*ln(1 + exp(x/s)) is a smooth max(x, 0). The dip of the total current at
Ug3 = -4 ... -6 V on Рис. 216 (virtual cathode) is not modelled.

The sheets give Ug2 = 120 V only, so MU2 rests on the cut-off and the 3/2 law (no contact
potential term); it is an assumption until the tube is measured.

usage: fit_6zh2b.py            prints the parameters and the residuals per curve
       fit_6zh2b.py --sub FILE  also writes the ngspice subcircuit (CRLF, like sch/libs)
"""
import json, os, sys
import numpy as np
from scipy.optimize import least_squares

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "..", "doc", "data", "6zh2b_datasheet.json")

NAMES = ["K", "MU2", "MU3", "MUA", "EX", "FM", "D", "U0", "U1", "W3", "VA0", "VA1"]
X0 = [0.5e-3, 22.0, 60.0, 400.0, 1.5, 0.82, 20.0, -9.0, 0.0, 4.0, 15.0, 0.5]
LO = [1e-6, 5.0, 5.0, 50.0, 1.0, 0.5, 2.0, -20.0, -1.0, 0.3, 0.1, 0.0]
HI = [1e-1, 80.0, 500.0, 1e5, 4.0, 1.0, 500.0, 5.0, 1.0, 20.0, 80.0, 5.0]
S0, S3 = 0.3, 0.3


def sp(x, s):
    return s * np.logaddexp(0.0, x / s)


def currents(p, ua, ug1, ug2, ug3):
    K, MU2, MU3, MUA, EX, FM, D, U0, U1, W3, VA0, VA1 = p
    ik = K * sp(ug1 + ug2 / MU2 + ug3 / MU3 + ua / MUA, S0) ** EX
    ikm = ik * 1e3
    f = FM * np.tanh(sp(ug3 + ua / D - U0 - U1 * ikm, S3) / W3) * np.tanh(np.maximum(ua, 0) / (VA0 + VA1 * ikm))
    return ik * f, ik * (1 - f)


def points():
    d = json.load(open(DATA))["plots"]
    rows = []  # ua, ug1, ug2, ug3, which (0 = Ia, 1 = Ig2), value mA, curve
    for key, which, xname in (("ia_ua", 0, "ua"), ("ic2_ua", 1, "ua"), ("ia_ug3", 0, "ug3"), ("ic2_ug3", 1, "ug3")):
        for g, pts in d[key]["curves"].items():
            for x, y in pts:
                ua, ug3 = (x, 0.0) if xname == "ua" else (120.0, x)
                rows.append((ua, float(g), 120.0, ug3, which, y, f"{key} Ug1={g}"))
    return rows


def resid(p, rows):
    ua, ug1, ug2, ug3, w, y = (np.array([r[i] for r in rows]) for i in range(6))
    ia, ig2 = currents(p, ua, ug1, ug2, ug3)
    m = np.where(w == 0, ia, ig2) * 1e3
    return (m - y) / (0.05 + 0.03 * np.abs(y))  # digitizing error 0.05 mA plus 3 %


SUB = """*--------------------------------------------------------------------------
* 6Zh2B (6Ж2Б) dual-control pentode, behavioural model, ngspice syntax
* Generated by tools/spice/fit_6zh2b.py from doc/data/6zh2b_datasheet.json
* (Рис. 215, 216 of the handbook page); page: doc/nand2_j2_6zh2b.md, Model.
*
*    Pins           : A G3 G2 K G1 (heater is not modelled)
*
* KiCad symbol vacuum_tube:6Ж2Б (handbook numbering):
*    Sim.Pins "1=A 2=G3 3=G2 6=K 7=G1"
*
* Ik  = K*sp(Ug1 + Ug2/MU2 + Ug3/MU3 + Ua/MUA)^EX
* F   = FM*tanh(sp(Ug3 + Ua/D - U0 - U1*Ik[mA])/W3)*tanh(max(Ua,0)/(VA0 + VA1*Ik[mA]))
* Ia  = Ik*F, Ig2 = Ik*(1 - F); sp(x) = max(x,0) + s*ln(1 + exp(-|x|/s))
* Assumptions (not on the sheets): the Ug2 dependence (only Ug2 = 120 V is
* given; MU2 rests on the power-law fit, no contact potential); grid current
* of g1 and g3 (diodes, RG1/RG3); the split of Cin/Cout and the g3
* capacitances (CG3A from the 6AS6, the US dual-control pentode; CG3K, CG2K).
*--------------------------------------------------------------------------
.SUBCKT 6Zh2B A G3 G2 K G1
+ PARAMS: {params}
+ S0=0.3 S3=0.3 CG1K=3.0P CG1G2=1.9P CG1A=0.03P CG3A=1.6P CG3K=3.0P CAK=2.5P CG2K=2.0P
+ RG1=2000 RG3=5000
BX  x  0 V={{V(G1,K) + V(G2,K)/MU2 + V(G3,K)/MU3 + V(A,K)/MUA}}
RX  x  0 1G
BIK ik 0 V={{K*PWR(MAX(V(x),0) + S0*LOG(1 + EXP(-ABS(V(x))/S0)), EX)}}
RIK ik 0 1G
BU  u  0 V={{V(G3,K) + V(A,K)/D - U0 - U1*1000*V(ik)}}
RU  u  0 1G
BF  f  0 V={{FM*TANH((MAX(V(u),0) + S3*LOG(1 + EXP(-ABS(V(u))/S3)))/W3)
+ *TANH(MAX(V(A,K),0)/(VA0 + VA1*1000*V(ik)))}}
RF  f  0 1G
GA  A  K  CUR={{V(ik)*V(f)}}
GG2 G2 K  CUR={{V(ik)*(1 - V(f))}}
RAK A  K  1G
RG2K G2 K 1G
RG3K G3 K 1G
C1  G1 K  {{CG1K}}
C2  G1 G2 {{CG1G2}}
C3  G1 A  {{CG1A}}
C4  G3 A  {{CG3A}}
C5  G3 K  {{CG3K}}
C6  A  K  {{CAK}}
C7  G2 K  {{CG2K}}
R1  G1 5  {{RG1}}
D1  5  K  DG
R3  G3 6  {{RG3}}
D3  6  K  DG
.MODEL DG D(IS=1N RS=1)
.ENDS 6Zh2B
"""


def write_sub(p, path):
    params = " ".join(f"{n}={v:.6g}" for n, v in zip(NAMES, p))
    with open(path, "w", newline="") as fh:
        fh.write(SUB.format(params=params).replace("\n", "\r\n"))


def fit():
    rows = points()
    r = least_squares(resid, X0, bounds=(LO, HI), args=(rows,), x_scale="jac", max_nfev=20000)
    return r.x, rows


if __name__ == "__main__":
    p, rows = fit()
    if "--sub" in sys.argv:
        write_sub(p, sys.argv[sys.argv.index("--sub") + 1])
    for n, v in zip(NAMES, p):
        print(f"{n:4s} = {v:.6g}")
    ua, ug1, ug2, ug3, w, y = (np.array([r[i] for r in rows]) for i in range(6))
    ia, ig2 = currents(p, ua, ug1, ug2, ug3)
    m = np.where(w == 0, ia, ig2) * 1e3
    for c in dict.fromkeys(r[6] for r in rows):
        k = np.array([r[6] == c for r in rows])
        e = m[k] - y[k]
        i = np.argmax(np.abs(e))
        print(f"{c:18s} max |err| {abs(e[i]):.2f} mA at x={ (ua if 'ua' in c.split()[0] else ug3)[k][i]:.1f} "
              f"(data {y[k][i]:.2f}), rms {np.sqrt(np.mean(e**2)):.2f} mA")
